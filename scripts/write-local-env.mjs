#!/usr/bin/env node
/**
 * Writes .env.local from the running local Supabase stack.
 *
 * The local keys are deterministic and public — they ship in Supabase's own
 * documentation — but they are still written to a gitignored file so nothing
 * trains anyone to commit credentials.
 *
 * Usage: npm run db:start && npm run db:env
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ENV_FILES = ['.env.local', '.env.test.local'];

function readStatus() {
  try {
    const raw = execFileSync('npx', ['supabase', 'status', '-o', 'json'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return JSON.parse(raw);
  } catch (error) {
    console.error('Could not read Supabase status. Is the stack running?');
    console.error('Try: npm run db:start');
    if (error instanceof Error && error.message) console.error(`\n${error.message}`);
    process.exit(1);
  }
}

const status = readStatus();

const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY;
const serviceRoleKey = status.SERVICE_ROLE_KEY;

if (!apiUrl || !anonKey) {
  console.error('Supabase status did not include API_URL and ANON_KEY.');
  console.error(`Received keys: ${Object.keys(status).join(', ')}`);
  process.exit(1);
}

if (!/localhost|127\.0\.0\.1/.test(apiUrl)) {
  console.error(`Refusing to write env for a non-local API URL: ${apiUrl}`);
  process.exit(1);
}

const contents = `# Generated by \`npm run db:env\` — do not commit.
# Local Supabase only. Regenerate after \`npm run db:start\`.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
${serviceRoleKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}\n` : ''}
# Deliberately a placeholder. MusicBrainz requires a User-Agent identifying the
# maintainers, so the client refuses to make live requests while this value
# looks like a placeholder. Set it to the repository URL before ingesting.
MUSICBRAINZ_CONTACT=https://placeholder.invalid/longplayr
`;

for (const file of ENV_FILES) {
  writeFileSync(resolve(process.cwd(), file), contents);
  console.log(`Wrote ${file}`);
}

console.log(`\nAPI:    ${apiUrl}`);
if (status.STUDIO_URL) console.log(`Studio: ${status.STUDIO_URL}`);
if (status.MAILPIT_URL)
  console.log(`Email:  ${status.MAILPIT_URL}  (confirmation emails land here)`);
