#!/usr/bin/env node
/**
 * Writes .env.local from the running local Supabase stack.
 *
 * The local keys are deterministic and public — they ship in Supabase's own
 * documentation — but they are still written to a gitignored file so nothing
 * trains anyone to commit credentials.
 *
 * Usage: npm run db:start && npm run db:env
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ENV_FILES = ['.env.local', '.env.test.local'];

function readStatus() {
  try {
    const raw = execFileSync('npx', ['supabase', 'status', '-o', 'json'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return JSON.parse(raw);
  } catch (error) {
    console.error('Could not read Supabase status. Is the stack running?');
    console.error('Try: npm run db:start');
    if (error instanceof Error && error.message) console.error(`\n${error.message}`);
    process.exit(1);
  }
}

const status = readStatus();

const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY;
const serviceRoleKey = status.SERVICE_ROLE_KEY;

if (!apiUrl || !anonKey) {
  console.error('Supabase status did not include API_URL and ANON_KEY.');
  console.error(`Received keys: ${Object.keys(status).join(', ')}`);
  process.exit(1);
}

if (!/localhost|127\.0\.0\.1/.test(apiUrl)) {
  console.error(`Refusing to write env for a non-local API URL: ${apiUrl}`);
  process.exit(1);
}

const PLACEHOLDER_CONTACT = 'https://placeholder.invalid/longplayr';

/**
 * The MusicBrainz contact, preserving a deliberate one.
 *
 * **The placeholder exists so ingestion cannot reach the real API by
 * accident** — the client refuses to make live requests while the value looks
 * like one (`musicbrainz.ts`), and `deployment.md` records that anything
 * needing real data must run *"with the variable set explicitly and
 * knowingly"*.
 *
 * **That protects against accident, not against intent**, and it used to
 * protect against both: the value was hard-coded here, so `npm run db:env`
 * silently overwrote a contact somebody had set on purpose. **Setting it then
 * survived exactly until the next `db:start`.**
 *
 * So a real value already in `.env.local`, or exported in the environment, is
 * now carried forward. **A fresh clone still gets the placeholder**, which is
 * the part worth keeping.
 */
function resolveContact() {
  const fromEnv = process.env.MUSICBRAINZ_CONTACT;
  if (fromEnv && !fromEnv.includes('placeholder.invalid')) return fromEnv;

  for (const file of ENV_FILES) {
    const path = resolve(process.cwd(), file);
    if (!existsSync(path)) continue;
    const match = readFileSync(path, 'utf8').match(/^MUSICBRAINZ_CONTACT=(.+)$/m);
    const existing = match?.[1]?.trim();
    if (existing && !existing.includes('placeholder.invalid')) return existing;
  }

  return PLACEHOLDER_CONTACT;
}

const contact = resolveContact();

const contents = `# Generated by \`npm run db:env\` — do not commit.
# Local Supabase only. Regenerate after \`npm run db:start\`.
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
${serviceRoleKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}\n` : ''}
# MusicBrainz requires a User-Agent identifying the maintainers, and the client
# refuses to make live requests while this looks like a placeholder. A real
# value set here or exported is preserved across \`db:env\`; a fresh clone gets
# the placeholder.
MUSICBRAINZ_CONTACT=${contact}
`;

for (const file of ENV_FILES) {
  writeFileSync(resolve(process.cwd(), file), contents);
  console.log(`Wrote ${file}`);
}

console.log(
  contact === PLACEHOLDER_CONTACT
    ? '\nMusicBrainz: placeholder — live ingestion refused.'
    : `\nMusicBrainz: ${contact} — live requests ENABLED.`,
);
console.log(`\nAPI:    ${apiUrl}`);
if (status.STUDIO_URL) console.log(`Studio: ${status.STUDIO_URL}`);
if (status.MAILPIT_URL)
  console.log(`Email:  ${status.MAILPIT_URL}  (confirmation emails land here)`);
