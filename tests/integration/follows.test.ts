import { describe, expect, it } from 'vitest';

/**
 * CI EXPERIMENT — INERT PLACEHOLDER. NOT A REAL TEST FILE.
 *
 * This file exists on the branch `ci-experiment/inert-ordering` only. It must
 * never be merged. On `main` this path holds the real Follows integration
 * suite (19 tests, commit 398bf4b).
 *
 * WHY IT EXISTS
 *
 * CI run #63 on 398bf4b failed twice, deterministically, with eight assertion
 * failures in `tests/integration/curated-recovery.test.ts` — a file that
 * commit does not touch. The Follows tests themselves passed 19/19 on both
 * attempts.
 *
 * Vitest's `BaseSequencer.sort()` falls back to `statsB.size - statsA.size`
 * when it has no cached results, so a cold-cache run — which is every CI run,
 * because the checkout is fresh — orders integration files by byte size,
 * largest first. Adding a 16,347-byte file at position 8 displaced
 * `curated-recovery.test.ts` from position 8 to position 9, changing the file
 * that immediately precedes it from `reviews.test.ts` to `follows.test.ts`.
 *
 * Clearing the local Vitest cache reproduces CI's ordering exactly and the
 * suite still passes 466/466, so the changed position is necessary but not
 * sufficient. Something about the CI environment is also required.
 *
 * WHAT THIS FILE CONTROLS FOR
 *
 * It is padded to exactly the byte size of the real Follows suite, so it
 * occupies the identical sort position and `curated-recovery.test.ts` stays at
 * position 9. But it touches nothing: no Supabase client, no auth users, no
 * catalogue rows, no jobs, no environment mutation. It is pure arithmetic.
 *
 * Therefore:
 *
 *   CI still red  -> position alone is sufficient. The contents of the Follows
 *                    suite are irrelevant, and the defect lies in
 *                    `curated-recovery.test.ts`'s own isolation or in shared
 *                    integration-test infrastructure.
 *
 *   CI green      -> something the Follows suite *does* is required — most
 *                    likely its ~40 auth-user creations and the cascading
 *                    deletes in its `afterAll` — and its resource lifecycle
 *                    needs separate investigation.
 *
 * Nothing else on the branch differs from 398bf4b.
 */

describe('inert ordering placeholder', () => {
  it('performs no I/O', () => {
    expect(1 + 1).toBe(2);
  });

  it('holds the sort position without touching the database', () => {
    expect('follows').toHaveLength(7);
  });
});

